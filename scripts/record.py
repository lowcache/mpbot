#!/usr/bin/env python3
"""Launches a visible browser.

Default: Playwright codegen records every click into flow.py.
With --login-only: just opens a window so she can refresh the session;
no recording is done.
"""
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).parent.parent
FLOW = ROOT / "flow.py"
STORAGE = ROOT / "storage.json"
SITE = "https://megapersonals.eu/"
TMP_OUT = "/tmp/mp_recording.py"

LOGIN_ONLY = "--login-only" in sys.argv


def run_login_only():
    from playwright.sync_api import sync_playwright
    with sync_playwright() as p:
        browser = p.chromium.launch(
            headless=False,
            args=["--no-sandbox", "--disable-dev-shm-usage"],
        )
        ctx_kwargs = {}
        if STORAGE.exists():
            ctx_kwargs["storage_state"] = str(STORAGE)
        context = browser.new_context(**ctx_kwargs)
        page = context.new_page()
        page.goto(SITE)
        try:
            page.wait_for_event("close", timeout=0)
        except Exception:
            pass
        try:
            context.storage_state(path=str(STORAGE))
        except Exception:
            pass
        try:
            browser.close()
        except Exception:
            pass


def run_codegen():
    cmd = [
        sys.executable, "-m", "playwright", "codegen",
        "--target", "python",
        "--output", TMP_OUT,
        "--save-storage", str(STORAGE),
    ]
    if STORAGE.exists():
        cmd.extend(["--load-storage", str(STORAGE)])
    cmd.append(SITE)
    env = os.environ.copy()
    env.setdefault("DISPLAY", ":0")
    subprocess.run(cmd, env=env)


def extract_actions(raw):
    """Pull just the action lines from codegen's full-script output."""
    lines = raw.splitlines()
    body = []
    capturing = False
    for ln in lines:
        s = ln.strip()
        if "context.new_page()" in s:
            capturing = True
            continue
        if not capturing:
            continue
        if s.startswith("context.close()") or s.startswith("browser.close()"):
            break
        body.append(ln)
    non_empty = [ln for ln in body if ln.strip()]
    if non_empty:
        indent = len(non_empty[0]) - len(non_empty[0].lstrip())
        body = [ln[indent:] if ln[:indent].isspace() else ln for ln in body]
    return [ln for ln in body if ln.strip()]


def main():
    if LOGIN_ONLY:
        run_login_only()
        return

    run_codegen()
    if not Path(TMP_OUT).exists():
        print("  Recording didn't produce a file. Nothing saved.")
        return

    raw = Path(TMP_OUT).read_text()
    actions = extract_actions(raw)
    if not actions:
        print("  Recording was empty. Nothing saved.")
        return

    body = "\n".join("    " + ln for ln in actions)
    FLOW.write_text(
        '"""Recorded flow. Regenerated by scripts/record.py."""\n\n'
        f'def run(page):\n{body}\n'
    )
    try:
        Path(TMP_OUT).unlink()
    except Exception:
        pass
    print("  Flow saved.")


if __name__ == "__main__":
    main()
